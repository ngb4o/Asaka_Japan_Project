/**
 * Generate PWA icons + iOS splash screens from the brand logo.
 * Logo size is a fixed fraction of the SHORTER side so it looks
 * the same on tall phones, wide phones, and tablets.
 *
 * Usage: node scripts/generate-pwa-assets.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const logoPath = path.join(root, "public/images/brand/logo.png");
const iconsDir = path.join(root, "public/icons");
const splashDir = path.join(root, "public/splash");
const splashMetaPath = path.join(root, "lib/pwa/apple-splash.ts");

const WHITE = { r: 255, g: 255, b: 255, alpha: 1 };
/** Splash: logo = 28% of the shorter edge (vmin). */
const SPLASH_LOGO_RATIO = 0.28;
/** Home-screen "any" icon: logo fills 78% — padding survives iOS rounded mask. */
const ANY_LOGO_RATIO = 0.78;
/** Maskable: logo fills 62% — stays inside the 80% safe zone after circle crop. */
const MASKABLE_LOGO_RATIO = 0.62;

/** Pixel size + CSS device size + pixel ratio (Apple HIG / pwa-asset-generator). */
const SPLASHES = [
  { w: 1320, h: 2868, dw: 440, dh: 956, dpr: 3 }, // iPhone 16 Pro Max
  { w: 1206, h: 2622, dw: 402, dh: 874, dpr: 3 }, // iPhone 16 Pro
  { w: 1290, h: 2796, dw: 430, dh: 932, dpr: 3 }, // iPhone 15 Pro Max / 14 Pro Max
  { w: 1179, h: 2556, dw: 393, dh: 852, dpr: 3 }, // iPhone 15 Pro / 14 Pro
  { w: 1284, h: 2778, dw: 428, dh: 926, dpr: 3 }, // iPhone 14 Plus / 13 Pro Max / 12 Pro Max
  { w: 1170, h: 2532, dw: 390, dh: 844, dpr: 3 }, // iPhone 14 / 13 / 13 Pro / 12 / 12 Pro
  { w: 1125, h: 2436, dw: 375, dh: 812, dpr: 3 }, // iPhone X / XS / 11 Pro
  { w: 1242, h: 2688, dw: 414, dh: 896, dpr: 3 }, // iPhone XS Max / 11 Pro Max
  { w: 828, h: 1792, dw: 414, dh: 896, dpr: 2 }, // iPhone XR / 11
  { w: 1242, h: 2208, dw: 414, dh: 736, dpr: 3 }, // iPhone 8 Plus / 7 Plus / 6s Plus
  { w: 750, h: 1334, dw: 375, dh: 667, dpr: 2 }, // iPhone SE / 8 / 7 / 6s
  { w: 640, h: 1136, dw: 320, dh: 568, dpr: 2 }, // iPhone SE 1st
  { w: 2048, h: 2732, dw: 1024, dh: 1366, dpr: 2 }, // iPad Pro 12.9
  { w: 1668, h: 2388, dw: 834, dh: 1194, dpr: 2 }, // iPad Pro 11
  { w: 1640, h: 2360, dw: 820, dh: 1180, dpr: 2 }, // iPad Air 10.9 / 10th
  { w: 1536, h: 2048, dw: 768, dh: 1024, dpr: 2 }, // iPad mini / 9.7
];

function media(dw, dh, dpr, orientation) {
  return `(device-width: ${dw}px) and (device-height: ${dh}px) and (-webkit-device-pixel-ratio: ${dpr}) and (orientation: ${orientation})`;
}

async function logoOnCanvas(width, height, logoRatio) {
  const short = Math.min(width, height);
  const logoSize = Math.max(32, Math.round(short * logoRatio));
  const logo = await sharp(logoPath)
    .resize(logoSize, logoSize, {
      fit: "contain",
      background: WHITE,
    })
    .png()
    .toBuffer();

  return sharp({
    create: { width, height, channels: 4, background: WHITE },
  })
    .composite([
      {
        input: logo,
        left: Math.round((width - logoSize) / 2),
        top: Math.round((height - logoSize) / 2),
      },
    ])
    .png({ compressionLevel: 9, quality: 90 });
}

async function writeIcon(filename, size, logoRatio) {
  const out = path.join(iconsDir, filename);
  await (await logoOnCanvas(size, size, logoRatio)).toFile(out);
  console.log("icon", filename, `${size}x${size}`);
}

async function main() {
  if (!fs.existsSync(logoPath)) {
    throw new Error(`Missing logo: ${logoPath}`);
  }
  fs.mkdirSync(iconsDir, { recursive: true });
  fs.mkdirSync(splashDir, { recursive: true });

  await writeIcon("icon-32.png", 32, ANY_LOGO_RATIO);
  await writeIcon("icon-180.png", 180, ANY_LOGO_RATIO);
  await writeIcon("apple-touch-icon.png", 180, ANY_LOGO_RATIO);
  await writeIcon("icon-192.png", 192, ANY_LOGO_RATIO);
  await writeIcon("icon-512.png", 512, ANY_LOGO_RATIO);
  await writeIcon("icon-512-maskable.png", 512, MASKABLE_LOGO_RATIO);

  const meta = [];
  for (const spec of SPLASHES) {
    const portrait = `apple-${spec.w}x${spec.h}.png`;
    const landscape = `apple-${spec.h}x${spec.w}.png`;
    await (await logoOnCanvas(spec.w, spec.h, SPLASH_LOGO_RATIO)).toFile(
      path.join(splashDir, portrait)
    );
    await (await logoOnCanvas(spec.h, spec.w, SPLASH_LOGO_RATIO)).toFile(
      path.join(splashDir, landscape)
    );
    meta.push({
      url: `/splash/${portrait}`,
      media: media(spec.dw, spec.dh, spec.dpr, "portrait"),
    });
    meta.push({
      url: `/splash/${landscape}`,
      media: media(spec.dw, spec.dh, spec.dpr, "landscape"),
    });
    console.log("splash", portrait, landscape);
  }

  const file = `/** Auto-generated by scripts/generate-pwa-assets.mjs — do not edit. */\nexport const APPLE_STARTUP_IMAGES = ${JSON.stringify(meta, null, 2)} as const;\n`;
  fs.mkdirSync(path.dirname(splashMetaPath), { recursive: true });
  fs.writeFileSync(splashMetaPath, file);
  console.log("wrote", path.relative(root, splashMetaPath));
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
